/**
 * One taxonomy, and a proof it is really one.
 *
 * The Worker used to carry a hand-maintained second copy of the category
 * table, with departments the shop no longer draws ("Women's Clothing",
 * "Tops & Shirts", "Bags & Luggage", "Vintage & Designer"). The picker emits
 * the real table's paths, so canonCategory() matched nothing and returned
 * null:
 *
 *   • INSERT nulled the department → the item landed in NO department, so
 *     department browsing could never reach it. That is the whole of "buyers
 *     can't find anything I list", and it failed silently — the API answered
 *     201 every time.
 *   • PUT nulled it again → an edit never stuck.
 *   • reads ran the row through the same function, so a stored path was
 *     blanked on the way out and /api/market answered category:null.
 *
 * Four of the eight departments could never hold a listing, while the UI
 * showed them as "0 items". Nothing crashed, which is exactly why it survived
 * rounds of "works on my machine" testing.
 *
 * What keeps it fixed is not the generator being run — anyone can forget — but
 * this file. It evaluates the module the Worker would ship and diffs it
 * against the real table, so drift fails CI instead of failing a seller.
 *
 * The Worker checkout is deliberately NOT required: the emitter is a pure
 * function here, so the invariant is checked on any machine, with or without
 * the sibling repo.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import {
  CATEGORIES, DEPARTMENTS as REAL_DEPTS, LEGACY as REAL_LEGACY,
  resolveCategory as realResolve,
} from "../functions/_lib/categories.js";
import { renderWorkerTaxonomy } from "../scripts/gen-worker-taxonomy.mjs";

/**
 * The browser's copy of the table (window.FASH_CAT), as data.
 *
 * It is generated by scripts/gen-categories.mjs from the same file the Worker's
 * table comes from, and it is what the seller's <select> is built from. Reading
 * the REAL file rather than a fixture means this test fails if the shipped
 * picker and the shipped API disagree about what a department is.
 */
function readBrowserTable() {
  const raw = readFileSync(fileURLToPath(new URL("../assets/categories.js", import.meta.url)), "utf8");
  const body = raw
    .replace(/^\s*\/\*[\s\S]*?\*\/\s*/, "")   // the generated-by banner
    .replace(/^\s*window\.FASH_CAT\s*=\s*/, "")
    .replace(/;\s*$/, "");
  return JSON.parse(body);
}

/**
 * Evaluate the generated module in a real ESM context.
 *
 * `new Function` would see `export` as a syntax error, so the source is written
 * to a temp file and imported. The point is that the SAME module the Worker
 * ships is what gets asserted on — a reimplementation in the test would only
 * prove the test agrees with itself.
 */
async function loadGenerated() {
  const { mkdtempSync, writeFileSync } = await import("node:fs");
  const { tmpdir } = await import("node:os");
  const { join } = await import("node:path");
  const { pathToFileURL } = await import("node:url");
  const dir = mkdtempSync(join(tmpdir(), "fash-tax-"));
  const file = join(dir, "categories.mjs");
  writeFileSync(file, renderWorkerTaxonomy());
  return import(pathToFileURL(file).href);
}

const generated = await loadGenerated();
const { PATHS, DEPARTMENTS, LEGACY, resolveCategory, prefixesFor, belongsUnder } = generated;

test("the Worker ships the real departments, not the retired ones", () => {
  assert.deepEqual([...DEPARTMENTS], [...REAL_DEPTS]);
  // The names that used to be in the Worker's own copy and matched nothing
  // the picker can emit. If any of these come back, the second copy is back.
  for (const retired of ["Women's Clothing", "Men's Clothing", "Kids & Baby",
                         "Bags & Luggage", "Vintage & Designer", "Sports & Outdoor"]) {
    assert.ok(!DEPARTMENTS.includes(retired), `retired department resurrected: ${retired}`);
  }
});

test("every path in the real table is a path the Worker accepts", () => {
  for (const c of CATEGORIES) {
    // Round-trips exactly, not merely "resolves to something". The failure
    // this guards was a resolve that returned null; the next-worst is one
    // that quietly files an item in a neighbouring department.
    assert.equal(resolveCategory(c.path), c.path, c.path);
    assert.ok(PATHS.has(c.path), `PATHS is missing ${c.path}`);
  }
  assert.equal(PATHS.size, new Set(CATEGORIES.map((c) => c.path)).size);
});

test("the picker emits a path that survives the API, for every department", () => {
  // Walk the generated browser table — the literal thing the seller's <select>
  // offers — and prove each option is still filed after a round trip. This is
  // the assertion that would have caught the original bug on day one.
  const browserTable = readBrowserTable();
  assert.equal(browserTable.departments.length, DEPARTMENTS.length);
  for (const c of browserTable.categories) {
    assert.equal(resolveCategory(c.path), c.path, `picker path lost: ${c.path}`);
  }
});

test("every legacy alias in the real table is honoured by the Worker", () => {
  for (const [k, v] of Object.entries(REAL_LEGACY)) {
    assert.equal(resolveCategory(k), v, `alias lost: ${k}`);
  }
  assert.deepEqual(Object.keys(LEGACY).sort(), Object.keys(REAL_LEGACY).sort());
});

test("the exact values prod was holding still resolve to a real department", () => {
  // Pulled from the live D1 table on 2026-10-11. Rows written before the real
  // table landed keep the old spelling forever; losing one is losing the item.
  const prod = {
    "Women's Clothing/Tops & Shirts": "Women/Tops",
    "Bags & Luggage/Handbags": "Women/Bags & Handbags",
    "Men's Clothing/Outerwear": "Men/Coats & Jackets",
    "Women's Clothing/Dresses": "Women/Dresses",
    "Tops": "Women/Tops",
  };
  for (const [held, want] of Object.entries(prod)) {
    assert.equal(resolveCategory(held), want, held);
    // …and the shopper browsing the destination actually sees it. The route
    // matches with LIKE on a prefix (the SQL wraps both sides in LOWER, and
    // LEGACY spells its keys lowercase), so what has to hold is that one of
    // the prefixes, upper-cased as a LIKE pattern, reaches the stored value.
    assert.ok(
      prefixesFor(want).some((p) => held.toLowerCase().startsWith(p.toLowerCase())),
      `no prefix for ${want} reaches the stored ${held}`
    );
    // And the authoritative test agrees once the row is canonicalized.
    assert.ok(belongsUnder(held, want), `${held} is not under ${want}`);
  }
});

test("the value the AI used to emit still lands somewhere real", () => {
  // sanitizeIdent feeds vision output straight through here. A flat word has
  // to resolve, or an AI-filed item is outside every department.
  for (const flat of ["Tops", "Bottoms", "Dresses", "Outerwear", "Shoes", "Accessories", "tops", "/tops"]) {
    assert.ok(resolveCategory(flat), `AI flat word unresolvable: ${flat}`);
  }
  assert.equal(resolveCategory("nonsense"), null);
});

test("junk stays null — the resolver never invents a department", () => {
  for (const junk of [null, undefined, "", "   ", "  /  ", 42, {}, []]) {
    assert.equal(resolveCategory(junk), null, JSON.stringify(junk));
  }
});

test("a bare department stays a department in the Worker, so nothing under it is filtered out", () => {
  // The department chips in the Shop send "Women", not "Women/Tops". The route
  // widens it through LIKE prefixes and then checks each canonicalized row
  // with belongsUnder — so what has to hold is that every path beneath the
  // department is classified as beneath it, and that the prefixes really do
  // reach the legacy spellings that would otherwise sit outside by string.
  for (const dept of DEPARTMENTS) {
    assert.equal(resolveCategory(dept), dept, dept);
    const under = [...PATHS].filter((p) => p.startsWith(dept + "/"));
    assert.ok(under.length > 0, `${dept} has no items under it`);
    for (const p of under) assert.ok(belongsUnder(p, dept), `${dept} misses ${p}`);
    // The prefix that has to exist is the department's own name: LIKE
    // "Women%" is what finds rows filed as bare "Women" and as "Women/…".
    assert.ok(prefixesFor(dept).includes(dept), `${dept} has no prefix of its own`);
  }
  // A leaf request stays a leaf request, not a department-wide sweep.
  assert.ok(belongsUnder("Women/Tops", "Women/Tops"));
  assert.ok(!belongsUnder("Women/Dresses", "Women/Tops"));
  // Pages, by contrast, collapses a bare department to its first row.
  assert.equal(realResolve("Women").path, "Women/Tops");
});

test("a request that names no place in the table matches nothing, not everything", () => {
  // `?category=nonsense` answered all 7 live listings before this, because
  // belongsUnder re-resolved the request and read an unresolvable one as "no
  // filter". A department a shopper asked for that does not exist has to come
  // back empty — showing the whole shop under the wrong heading is worse than
  // showing nothing, because it looks like it worked.
  assert.equal(prefixesFor("nonsense").length, 0);
  assert.equal(belongsUnder("Women/Tops", null), false);
  assert.equal(belongsUnder("Women/Tops", "nonsense"), false);
  // Rows that resolve to nothing are never under anything either.
  assert.equal(belongsUnder(null, "Women"), false);
  assert.equal(belongsUnder("", "Women"), false);
  // …and an empty request is still not a filter.
  assert.equal(prefixesFor("").length, 0);
});

test("the Worker's resolver and the Pages one agree on every path and alias", () => {
  // The Pages copy (functions/_lib/categories.js) returns the whole category
  // ROW so callers can reach ebay/etsy ids; the Worker's copy returns just the
  // path string, because the only thing it ever does is store a string in D1
  // and build a WHERE clause. Compare on .path.
  //
  // One deliberate divergence, asserted below rather than papered over: given
  // a bare department ("Women"), Pages collapses to that department's first
  // row, while the Worker keeps "Women" so the market filter can prefix-match
  // everything under it.
  const agree = [
    ...CATEGORIES.map((c) => c.path),
    ...Object.keys(REAL_LEGACY),
    "Tops", "nonsense", "",
  ];
  for (const v of agree) {
    const pages = realResolve(v);
    assert.equal(
      resolveCategory(v),
      pages ? pages.path : null,
      `disagreement on ${JSON.stringify(v)}`
    );
  }
});
