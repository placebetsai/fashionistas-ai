#!/usr/bin/env node
/**
 * Generate the API Worker's category table from functions/_lib/categories.js.
 *
 * WHY THIS EXISTS
 * The Worker used to carry its own hand-written copy of the taxonomy
 * ("Women's Clothing" / "Tops & Shirts" / "Bags & Luggage" / …). The shop's
 * picker emits the real table's paths ("Women/Tops", "Women/Bags & Handbags"),
 * so canonCategory() matched nothing and returned null for every department a
 * seller could pick:
 *
 *   • INSERT nulled the department → the item landed in NO department, so
 *     department browsing could never reach it. That is the whole of "buyers
 *     can't find anything I list", and it failed silently: the API answered
 *     201 every time.
 *   • PUT nulled it again → an edit never stuck.
 *   • reads ran the row through the same function, so a stored path was
 *     blanked on the way out and /api/market said category:null.
 *
 * FOUR of the eight departments the shop draws could therefore never hold a
 * listing, while the UI cheerfully showed them as "0 items". The code was
 * correct against a table that no longer described the product — which is why
 * it survived several rounds of "works on my machine" testing.
 *
 * ONE TABLE, ONE SOURCE. This copies the real table into the Worker so the two
 * cannot drift again. Regenerate after editing functions/_lib/categories.js:
 *
 *   FASH_WORKER_SRC=../nexus-ai-suite/workers/fashionistas-api/src \
 *     node scripts/gen-worker-taxonomy.mjs
 *
 * The output is committed, so a deploy never depends on running this.
 *
 * The emitter is a pure function (renderWorkerTaxonomy) rather than a script
 * body on purpose: tests/category-parity.test.mjs imports it and diffs the
 * result against the real table, which is what actually catches drift. Running
 * the generator is not a test — anyone can forget to.
 */
import { writeFileSync, mkdirSync, readFileSync, existsSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, resolve } from "node:path";

const { DEPARTMENTS, CATEGORIES, LEGACY } = await import(
  new URL("../functions/_lib/categories.js", import.meta.url).href
);

// The Worker only needs paths + the legacy aliases. The per-marketplace ids
// (ebay/etsy/depop) belong to the posting routes, which live in the Pages
// Functions, not in the Worker.
const PATHS = [...new Set(CATEGORIES.map((c) => c.path))];

/**
 * The generated module, as source text.
 *
 * Exposed so a test can evaluate it without the Worker checkout being on the
 * same machine, and so `--check` can diff it against what is committed.
 */
export function renderWorkerTaxonomy() {
  const esc = (s) => String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'");
  const out = [];
  const p = (s = "") => out.push(s);

  p("/* GENERATED by scripts/gen-worker-taxonomy.mjs — do not edit.");
  p(" *");
  p(" * Source of truth: fashionistas.ai/functions/_lib/categories.js.");
  p(" * Regenerate:      node scripts/gen-worker-taxonomy.mjs");
  p(" *");
  p(" * This table used to be a hand-maintained second copy with different");
  p(" * department names than the shop's picker emits, so canonCategory()");
  p(" * returned null for every real department path and listings landed in no");
  p(" * department at all. Copy it from one source instead of translating it. */");
  p();
  p("export const DEPARTMENTS = [");
  for (const d of DEPARTMENTS) p(`  '${esc(d)}',`);
  p("];");
  p();
  p("// Every canonical stored value, exactly as the picker emits it: 'Dept/Sub'.");
  p("export const PATHS = new Set([");
  for (const path of PATHS) p(`  '${esc(path)}',`);
  p("]);");
  p();
  p("// Array form of PATHS, for the linear scans in resolveCategory().");
  p("const paths = [...PATHS];");
  p();
  p("// Flat words and the previous tree ('Women's Clothing/Tops & Shirts') ->");
  p("// where they live now. Rows written before this table existed still hold");
  p("// the old spelling, and so does some AI output; resolve them rather than");
  p("// discarding the item's department.");
  p("export const LEGACY = {");
  for (const [k, v] of Object.entries(LEGACY).sort(([a], [b]) => (a < b ? -1 : 1))) {
    p(`  '${esc(k)}': '${esc(v)}',`);
  }
  p("};");
  p();
  p("/** Any stored/AI/picker category value -> canonical path, or null. */");
  p("export function resolveCategory(raw) {");
  p("  if (typeof raw !== 'string') return null;");
  p("  const v = raw.trim().replace(/^\\/+/, '').replace(/\\s*\\/\\s*/g, '/');");
  p("  if (!v) return null;");
  p("  // exact canonical path, any capitalisation");
  p("  for (const p of PATHS) if (p.toLowerCase() === v.toLowerCase()) return p;");
  p("  const legacy = LEGACY[v.toLowerCase()];");
  p("  if (legacy) return legacy;");
  p("  // 'Dept/Sub' where only the department is known -> leave the department");
  p("  // alone rather than nulling it: a partially-filed item is still findable.");
  p("  const parts = v.split('/');");
  p("  const dept = DEPARTMENTS.find((d) => d.toLowerCase() === parts[0].toLowerCase());");
  p("  if (!dept) return null;");
  p("  if (parts.length === 1) return dept;");
  p("  const sub = parts.slice(1).join('/');");
  p("  const under = paths.find((p) => p.toLowerCase() === (dept + '/' + sub).toLowerCase());");
  p("  if (under) return under;");
  p("  const sameSub = paths.find((p) => {");
  p("    const ps = p.split('/');");
  p("    return ps[0] === dept && ps.slice(1).join('/').toLowerCase() === sub.toLowerCase();");
  p("  });");
  p("  return sameSub || dept;");
  p("}");
  p();
  p("/* The market route pre-filters in SQL against the raw column, which still");
  p("   holds the old spellings for rows written before this table existed.");
  p("   Resolve the requested path and hand SQL every spelling that maps to it,");
  p("   so a shopper browsing \"Women/Tops\" also gets rows stored as \"Tops\" or");
  p("   \"Women's Clothing/Tops & Shirts\". */");
  p("const BY_RESOLVED = new Map();");
  p("for (const k of Object.keys(LEGACY)) {");
  p("  const r = resolveCategory(k);");
  p("  if (!r) continue;");
  p("  if (!BY_RESOLVED.has(r)) BY_RESOLVED.set(r, []);");
  p("  BY_RESOLVED.get(r).push(k);");
  p("}");
  p();
  p("/**");
  p(" * Every stored spelling (plus the canonical path itself) that belongs under");
  p(" * a requested department path. Used to build the market route's SQL filter.");
  p(" */");
  p("export function spellingsFor(raw) {");
  p("  const path = resolveCategory(raw);");
  p("  if (!path) return raw && typeof raw === 'string' && raw.trim() ? [raw.trim()] : [];");
  p("  const out = new Set([path]);");
  p("  for (const s of BY_RESOLVED.get(path) || []) out.add(s);");
  p("  // A bare department request means everything filed under it.");
  p("  if (!path.includes('/')) {");
  p("    const pfx = path.toLowerCase() + '/';");
  p("    for (const p of PATHS) if (p.toLowerCase().startsWith(pfx)) out.add(p);");
  p("  }");
  p("  return [...out];");
  p("}");
  p();

  return out.join("\n");
}

/**
 * Where the Worker's src directory is.
 *
 * Two ways, in order: FASH_WORKER_SRC, then a `nexus-ai-suite` checkout sitting
 * beside or above this repo. There is no hardcoded absolute path — a script
 * that only works on one laptop is a script nobody else can run, and this repo
 * is the one that gets cloned.
 */
function workerSrcDir() {
  if (process.env.FASH_WORKER_SRC) return resolve(process.env.FASH_WORKER_SRC);
  const here = dirname(fileURLToPath(import.meta.url));
  let dir = resolve(here, "..");
  for (let i = 0; i < 4; i++) {
    const candidate = resolve(dir, "nexus-ai-suite/workers/fashionistas-api/src");
    // A real check, not a guess: the directory has to exist. existsSync rather
    // than a write probe — a probe would leave a stray file in someone's repo.
    if (existsSync(candidate)) return candidate;
    dir = resolve(dir, "..");
  }
  return null;
}

/** Write the module, or with --check, fail if the committed copy is stale. */
function main(argv) {
  const dir = workerSrcDir();
  if (!dir) {
    console.error(
      "gen-worker-taxonomy: cannot find the API Worker checkout.\n" +
      "  Set FASH_WORKER_SRC to the Worker's src directory, e.g.\n" +
      "  FASH_WORKER_SRC=../nexus-ai-suite/workers/fashionistas-api/src node scripts/gen-worker-taxonomy.mjs"
    );
    process.exit(1);
  }
  const out = resolve(dir, "categories.js");
  const src = renderWorkerTaxonomy();

  if (argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(out, "utf8"); } catch { /* nothing committed yet */ }
    if (current !== src) {
      console.error(`gen-worker-taxonomy --check: ${out} is stale. Regenerate it.`);
      process.exit(1);
    }
    console.log(`gen-worker-taxonomy --check: ${out} is up to date`);
    return;
  }

  mkdirSync(dir, { recursive: true });
  writeFileSync(out, src);
  console.log(`gen-worker-taxonomy: wrote ${out}`);
  console.log(`  ${PATHS.length} paths, ${Object.keys(LEGACY).length} legacy aliases, ${DEPARTMENTS.length} departments`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2));
}
